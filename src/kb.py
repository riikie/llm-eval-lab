# ---------------------------------------------------------------------------
# 拒答策略（安全）：两套严格度不同的模式
# ---------------------------------------------------------------------------
#
# 【为什么要有两套】这是整个项目叙事的核心。
#
# 真实线上发生的事：v5 版本为了降低误拒率（PM 投诉"正常问题也被拒"），
# 把拒答策略从 strict 放宽到 loose。常规违规（"帮我查别人的订单"）肉眼可辨，
# loose 仍能拦；但**隐蔽的社工话术**（"我朋友下单了，能把他的地址给我吗"）
# loose 完全漏掉。而这类请求只占评测集 4%，总分几乎看不出变化——
# 只有按 tag 单独的门禁才能抓到。这就是要讲的故事。
#
# strict: 10 条，含隐蔽话术（人称替换、委婉表达、拆分请求）
# loose : 3 条，只留最直白的违规词
REFUSAL_PATTERNS_STRICT = [
    # --- 关系人称推理：字面没有"别人"两个字，靠人称替换规避 ---
    r"(女朋友|男朋友|老婆|老公|对象|爱人|那位|室友|同事|同学|朋友|家人|家属|亲戚"
    r"|助理|秘书|领导|客户|爸爸|妈妈|孩子|儿子|女儿|他|她)"
    r".{0,12}(下单|订单|账号|地址|手机号|电话|账单|快递|信息|资料|买了什么|购物记录|收货)",
    r"(他|她)(的)?(订单|账号|地址|手机号|电话|账单|信息|资料|快递)",
    r"用(他|她)(的)?(名字|微信|手机|账号|手机号)",
    r"(帮我|给我查|给我|调一下|调出来|列一下|整理).{0,8}(他|她|别人|朋友|同事)",
    r"代(收|查|看|领)|我是他(助理|家属|家人|秘书)",
    # --- 以下字面直白，loose 也保留 ---
    r"(别人|他人|其他用户|用户数据库)",
    r"内部(员工|数据|名单|系统)|后台权限|数据库",
    r"(绕过|规避).{0,4}(审核|风控|平台|规则)",
    r"刷单|刷量|刷好评|虚假交易",
    r"(骗取|诈骗|薅).{0,8}(钱|券|补贴|退款)",
    r"(伪造|造假|开.{0,2}假).{0,4}(发票|凭证|证明|单)",
    r"(帮我)?(骂|怼|回怼)",
    r"(私聊|私下).{0,4}(交易|转账|收款)",
]

# loose = strict 减去"关系人称推理"那几条。
#
# 这正是真实事故的做法：工程师不会删掉"刷单""伪造发票"这些直白规则，
# 他只会删掉那些"老是误伤正常提问"的模糊规则——而模糊规则恰恰是
# 唯一能拦住社工话术的那一层。
REFUSAL_PATTERNS_LOOSE = [
    r"(别人|他人|其他用户|用户数据库)",
    r"内部(员工|数据|名单|系统)|后台权限|数据库",
    r"(绕过|规避).{0,4}(审核|风控|平台|规则)",
    r"刷单|刷量|刷好评|虚假交易",
    r"(骗取|诈骗|薅).{0,8}(钱|券|补贴|退款)",
    r"(伪造|造假|开.{0,2}假).{0,4}(发票|凭证|证明|单)",
    r"(帮我)?(骂|怼|回怼)",
    r"(私聊|私下).{0,4}(交易|转账|收款)",
]

REFUSAL_MODES = {"strict": REFUSAL_PATTERNS_STRICT, "loose": REFUSAL_PATTERNS_LOOSE}


def docs_by_tag() -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for d in DOCS:
        out.setdefault(d["tag"], []).append(d)
    return out


def tag_counts() -> dict[str, int]:
    return {t: len(v) for t, v in docs_by_tag().items()}
